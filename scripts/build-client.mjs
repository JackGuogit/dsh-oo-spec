/**
 * Build `client.js` from `client.src.js` plus the packaged spec documents.
 *
 * The client module must be a single file the host module loader can evaluate,
 * so the documents are inlined as a JSON literal instead of being fetched at
 * runtime. Run after editing `client.src.js` or the spec files:
 *
 *   node scripts/build-client.mjs
 */

import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { DOCS, readDocs } from '../lib/corpus.js'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const TEMPLATE = join(ROOT, 'client.src.js')
const OUTPUT = join(ROOT, 'client.js')
const PLACEHOLDER = '/*__OO_SPEC_DOCUMENTS__*/ []'
const GROUP = {
  constitution: 'core',
  gates: 'core',
  index: 'core',
  card: 'card',
  table: 'table',
  example: 'example',
  eval: 'eval',
  anchors: 'anchors',
}

const { docs } = await readDocs(
  DOCS.map((doc) => doc.id),
  400000,
)
if (docs.length !== DOCS.length) throw new Error(`expected ${DOCS.length} documents, read ${docs.length}`)

const data = docs.map((doc) => ({
  id: doc.id,
  title: doc.title,
  kind: doc.kind,
  group: GROUP[doc.kind] ?? 'core',
  text: doc.text,
}))

const template = await readFile(TEMPLATE, 'utf8')
if (!template.includes(PLACEHOLDER)) throw new Error('client.src.js lost its document placeholder')

// JSON is valid JavaScript once the `<` characters cannot start a tag; escape
// them so the literal stays inert in any embedding context.
const literal = JSON.stringify(data).replace(/</g, '\\u003c')
const built = template.split(PLACEHOLDER).join(literal)
const banner = '// Generated by scripts/build-client.mjs — edit client.src.js instead.\n'
await writeFile(OUTPUT, banner + built, 'utf8')

const chars = data.reduce((sum, doc) => sum + doc.text.length, 0)
console.log(`client.js: ${data.length} documents, ${chars} spec chars, ${Math.round((banner.length + built.length) / 1024)} KiB`)
